"""Static guard: every tool response model that owns an alias must serialize by alias.

Output schemas are generated by alias, but FastMCP 4 serializes structured
content by field name unless the model sets ``serialize_by_alias``. Pydantic
config is not inherited by nested models, so each aliased model needs the
setting itself.
"""

from __future__ import annotations

import pathlib
import typing
from typing import Annotated, Any

import pytest
from pydantic import BaseModel, Field, RootModel

from itential_mcp.utilities.tool import itertools


def _tools_path() -> str:
    return str(
        pathlib.Path(__file__).parent.parent.parent / "src" / "itential_mcp" / "tools"
    )


def _iter_models(annotation: Any) -> typing.Iterator[type[BaseModel]]:
    """Yield every pydantic model class referenced by an annotation."""
    if isinstance(annotation, type) and issubclass(annotation, BaseModel):
        yield annotation
        return
    for arg in typing.get_args(annotation):
        yield from _iter_models(arg)


def collect_models(annotation: Any) -> set[type[BaseModel]]:
    """Recursively collect all models reachable from a return annotation."""
    seen: set[type[BaseModel]] = set()
    stack = list(_iter_models(annotation))
    while stack:
        model = stack.pop()
        if model in seen:
            continue
        seen.add(model)
        for field in model.model_fields.values():
            stack.extend(_iter_models(field.annotation))
    return seen


def owns_alias(model: type[BaseModel]) -> bool:
    """Return True if the model declares any aliased field."""
    return any(
        f.alias is not None
        or f.validation_alias is not None
        or f.serialization_alias is not None
        for f in model.model_fields.values()
    )


def alias_violations(models: set[type[BaseModel]]) -> list[str]:
    """Return names of aliased models missing the required config."""
    return sorted(
        m.__name__
        for m in models
        if owns_alias(m)
        and not (
            m.model_config.get("serialize_by_alias") is True
            and m.model_config.get("populate_by_name") is True
        )
    )


def _all_tool_models() -> set[type[BaseModel]]:
    found: set[type[BaseModel]] = set()
    for func, _tags, _ann in itertools(_tools_path()):
        hints = typing.get_type_hints(func, include_extras=False)
        found |= collect_models(hints.get("return"))
    return found


class TestAliasSerializationGuard:
    def test_discovers_models(self):
        models = _all_tool_models()
        assert len(models) > 50
        assert any(owns_alias(m) for m in models)

    def test_all_aliased_tool_models_serialize_by_alias(self):
        assert alias_violations(_all_tool_models()) == []

    def test_guard_flags_missing_config(self):
        class Bad(BaseModel):
            thing: Annotated[str, Field(alias="_thing")]

        class Wrapper(RootModel):
            root: list[Bad]

        class Good(BaseModel):
            plain: str

        found = collect_models(Wrapper | None)
        assert Bad in found
        assert alias_violations(found | {Good}) == ["Bad"]

    def test_guard_accepts_correct_config(self):
        from itential_mcp.models.base import AliasedModel

        class Ok(AliasedModel):
            thing: Annotated[str, Field(alias="_thing")]

        assert alias_violations({Ok}) == []

    def test_guard_walks_nested_unions_and_dicts(self):
        class Inner(BaseModel):
            thing: Annotated[str, Field(alias="_thing")]

        class Outer(BaseModel):
            items: dict[str, list[Inner | None]]

        assert Inner in collect_models(Outer)
        assert alias_violations(collect_models(Outer)) == ["Inner"]


@pytest.mark.parametrize(
    "name", ["JobMetricElement", "TaskMetricElement", "HealthResponse"]
)
def test_known_aliased_models_covered(name):
    names = {m.__name__ for m in _all_tool_models()}
    assert name in names
